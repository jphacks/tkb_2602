// お祓いの作法（1番）：妖怪ごとの「どうすれば残らなくなるか」のひとこと
// 妖怪は「やり残されていたこと」の名前で決める（妖怪の割り当ては一覧の並び順なので、名前から選ぶほうが正確）。
// AIで作った妖怪にも使えるように、名前に含まれる言葉で選び、当てはまらなければ共通の作法を出す。
// 誰かを責める言い方はしない（「〜しよう」「〜すると効く」）。

const RULES: Array<{ pattern: RegExp; advice: string }> = [
  { pattern: /洗|食器/, advice: "使い終わったら、その日のうちに洗う。洗い待ちのカゴを決めておくと効く" },
  { pattern: /ゴミ|ごみ/, advice: "8割たまったら、気づいた人がまとめて出す。ゴミの日を貼り出しておくと効く" },
  { pattern: /冷蔵|冷凍|期限/, advice: "入れる物には日付を書く。中を見る日を月に1回決めておくと効く" },
  { pattern: /電気|照明|消灯/, advice: "最後に部屋を出る人が消す。出口に「消灯」の札を貼ると効く" },
  { pattern: /空調|エアコン|冷房|暖房/, advice: "最後に出る人が切る。切タイマーを使うと効く" },
  { pattern: /補充|切れ|備品|消耗|トナー|在庫/, advice: "少なくなったら補充メモに書く。予備の置き場所を決めておくと効く" },
  { pattern: /紙詰まり|プリンター|コピー/, advice: "気づいたら、その場で直す。使い方を機械の横に貼っておくと効く" },
  { pattern: /掃除|清掃|汚れ|ほこり|埃|排水/, advice: "さっと掃除する日を週に1回決める。道具を手の届く場所に置いておくと効く" },
  { pattern: /返却|戻/, advice: "使い終わったら、すぐ元の棚へ。置き場所に写真を貼っておくと効く" },
  { pattern: /机|デスク/, advice: "帰るときは、机を何もない状態に戻す。私物の置き場所を決めておくと効く" },
  { pattern: /出しっぱ|置きっぱ|放置|片付|片づ/, advice: "使ったら元の場所へ。置き場所にラベルを貼っておくと効く" },
];

const DEFAULT_ADVICE = "気づいたら、その場で片づけて観測しよう。置き場所や順番を研究室で決めておくと効く";

export function oharaiAdvice(taskName: string | null | undefined): string {
  if (!taskName) return DEFAULT_ADVICE;
  return RULES.find((rule) => rule.pattern.test(taskName))?.advice ?? DEFAULT_ADVICE;
}

